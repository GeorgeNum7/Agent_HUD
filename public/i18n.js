// Dashboard language. "auto" follows the browser (zh* → 中文, otherwise English); the toggle stores "zh" or "en".
// Static markup is translated through data-i18n="key" (text) and data-i18n-attr="attr:key;attr:key".
// Text the local service sends in Chinese (window names, quota sources, status messages) goes through server().
const STORE = 'agent-hud-lang';
let setting = 'auto';
try { const stored = localStorage.getItem(STORE); if (stored === 'zh' || stored === 'en') setting = stored; } catch {}
export let lang = resolve();
function resolve() {
  if (setting !== 'auto') return setting;
  return String(navigator.languages?.[0] || navigator.language || '').toLowerCase().startsWith('zh') ? 'zh' : 'en';
}
export function setLang(next) {
  setting = next === 'en' || next === 'zh' ? next : 'auto';
  lang = resolve();
  try { localStorage.setItem(STORE, setting); } catch {}
  applyStatic();
}

